/**
 * ============================================================================
 * OFFLINE-FIRST MULTI-PLATFORM ACCOUNTING SYSTEM
 * Service: Bidirectional Append-Only Sync Engine (Push / Pull Batch Worker)
 * Module:  src/services/SyncEngine.ts
 * ============================================================================
 *
 * ARCHITECTURAL SPECIFICATIONS & DISTRIBUTED SYSTEMS PATTERNS:
 * 1. Transactional Outbox Pattern (Push Pipeline):
 *    - Queries `sync_queue` for records where `sync_status = 'PENDING'`.
 *    - Atomic batching (up to 50 records) transitioned to 'SYNCING'.
 *    - Assembles an append-only JSON batch envelope.
 *    - Uploads to Google Drive v3 via multipart REST upload under `google_folder_id`.
 *    - Prunes or marks synced records on HTTP 200/201 acknowledgment.
 *    - Exponential backoff & retry counter on network or API failures.
 *
 * 2. Append-Only Pull Pipeline:
 *    - Tracks chronological high-water mark via `sync_meta` ('GLOBAL').
 *    - Queries Google Drive for files created after `last_sync_timestamp`.
 *    - Self-Origin Filtering: Ignores batches generated by the current device.
 *    - Applies idempotent upserts (`INSERT OR REPLACE INTO [table]`) inside a
 *      single atomic SQLite transaction with foreign key deferral.
 *    - Advances `last_sync_timestamp` to the latest applied batch's `createdTime`.
 *
 * 3. Reactive Orchestration & Concurrency Guard:
 *    - Sequential pipeline execution: Auth Verification -> Push -> Pull.
 *    - State machine status broadcasting: IDLE -> SYNCING_PUSH -> SYNCING_PULL -> SUCCESS / ERROR.
 *    - Background periodic worker with non-overlapping execution lock.
 */

import { SQLiteDatabase } from './NumberingService';
import {
  DriveAuthService,
  SETTINGS_KEYS,
  getSetting,
} from './DriveAuthService';

// ----------------------------------------------------------------------------
// 1. CONSTANTS & SYNC CONFIGURATION
// ----------------------------------------------------------------------------

export const SYNC_CONFIG = {
  BATCH_SIZE: 50,
  MAX_RETRIES: 5,
  UPLOAD_MULTIPART_URL: 'https://www.googleapis.com/upload/drive/v3/files?uploadType=multipart',
  DRIVE_FILES_URL: 'https://www.googleapis.com/drive/v3/files',
  GLOBAL_META_ENTITY: 'GLOBAL',
  DEFAULT_EPOCH_ISO: '1970-01-01T00:00:00.000Z',
  DEFAULT_SYNC_INTERVAL_MS: 60 * 1000, // 60 seconds
  FILE_PREFIX: 'BATCH_',
} as const;

// Strict whitelist of syncable entities to guarantee SQL injection safety
export const SYNCABLE_TABLES = new Set([
  'invoices',
  'invoice_items',
  'sales_returns',
  'sales_return_items',
  'journal_entries',
  'journal_lines',
  'app_settings',
  'items',
  'customers',
  'vendors'
]);

// ----------------------------------------------------------------------------
// 2. DATA TYPES & INTERFACES
// ----------------------------------------------------------------------------

export type SyncAction = 'INSERT' | 'UPDATE' | 'DELETE';

export type SyncStatus = 'IDLE' | 'SYNCING_PUSH' | 'SYNCING_PULL' | 'SUCCESS' | 'ERROR';

export interface SyncRecord {
  table: string;
  id: string;
  action: SyncAction;
  data: Record<string, any>;
}

export interface SyncBatchPayload {
  deviceId: string;
  batchId: string;
  generatedAt: string;
  records: SyncRecord[];
}

export interface DriveBatchFile {
  id: string;
  name: string;
  createdTime: string;
  size?: string;
}

export interface PushResult {
  pushedBatches: number;
  pushedRecords: number;
  batchIds: string[];
}

export interface PullResult {
  pulledBatches: number;
  pulledRecords: number;
  skippedSelfBatches: number;
  latestTimestamp: string | null;
}

export interface SyncResult {
  success: boolean;
  push: PushResult;
  pull: PullResult;
  error?: string;
  durationMs: number;
}

export interface SyncEventDetails {
  status: SyncStatus;
  pushedRecords?: number;
  pulledRecords?: number;
  errorMessage?: string;
  timestamp: string;
}

export type SyncStatusListener = (event: SyncEventDetails) => void;

interface SyncQueueRow {
  queue_id: number;
  entity_table: string;
  record_id: string;
  action_type: SyncAction;
  payload: string | Record<string, any>;
  retry_count: number;
}

// ----------------------------------------------------------------------------
// 3. DOMAIN EXCEPTIONS
