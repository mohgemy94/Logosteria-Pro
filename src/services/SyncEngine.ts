export async function syncNow(db: SQLiteDatabase): Promise<SyncResult> {
  return await SyncEngine.syncNow(db);
}

export function startPeriodicSync(
  db: SQLiteDatabase,
  intervalMs: number = SYNC_CONFIG.DEFAULT_SYNC_INTERVAL_MS
): () => void {
  return SyncEngine.startPeriodicSync(db, intervalMs);
}

