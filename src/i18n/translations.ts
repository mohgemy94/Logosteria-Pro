// Sort phrase keys by length descending to replace compound expressions first
const SORTED_ARABIC_KEYS = Object.keys(ARABIC_TO_ENGLISH_MAP).sort((a, b) => b.length - a.length);

/**
 * Intelligent Universal Text Translator
 * Translates any Arabic string, sentence, or fragment to English
 */
export function autoTranslateToEnglish(text: string): string {
  if (!text || typeof text !== 'string') return text;
  
  const trimmed = text.trim();
  if (!trimmed) return text;

  // 1. Exact match check
  if (ARABIC_TO_ENGLISH_MAP[trimmed]) {
    return ARABIC_TO_ENGLISH_MAP[trimmed];
  }

  // 2. Check if string contains Arabic characters
  const hasArabic = /[\u0600-\u06FF]/.test(trimmed);
  if (!hasArabic) return text;

  // 3. Sequential greedy phrase replacement
  let result = text;
  for (const key of SORTED_ARABIC_KEYS) {
    if (result.includes(key)) {
      const replacement = ARABIC_TO_ENGLISH_MAP[key];
      // Use split and join to replace all occurrences without regex escaping problems
      result = result.split(key).join(replacement);
    }
  }

  // 4. Translate common numbers formatting with currency
  result = result.split('ر.س').join('SAR');
  result = result.split('رس').join('SAR');
  result = result.split('ريال').join('SAR');
  result = result.split('٪').join('%');
  result = result.split('،').join(',');
  result = result.split('؛').join(';');
  result = result.split('؟').join('?');

  return result;
}

